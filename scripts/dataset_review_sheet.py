"""
scripts/dataset_review_sheet.py
===============================
Write docs/dataset/CORRECTIONS_REVIEW.md: one entry per audited task
correction, with the reason, the task as it now stands and its accepted
aliases, plus a checkbox for a human reviewer.

The corrections were made by an automated audit. A person should confirm each
one before the results are cited; this sheet is what they work through.

    python scripts/dataset_review_sheet.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from scripts.apply_dataset_corrections import CORRECTIONS  # noqa: E402
from shared.data_loader import load_answer_aliases, load_split  # noqa: E402

SOURCE = ROOT / "scripts" / "apply_dataset_corrections.py"
OUT = ROOT / "docs" / "dataset" / "CORRECTIONS_REVIEW.md"
_KEY = re.compile(r'^    "([a-z]+_\d+)": \{')

# Uncorrected tasks a scan of every gold answer flagged as still debatable.
#
# Both tasks flagged in the first review (cmp_002 and cmp_016) were rewritten after the human
# review of November 2026, so the list is empty. Add a task id and a concern to flag one.
WATCHLIST: dict[str, str] = {}


def reasons() -> dict[str, str]:
    """The comment written above each correction in apply_dataset_corrections.py."""
    found: dict[str, str] = {}
    pending: list[str] = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            pending.append(stripped.lstrip("# ").strip())
        elif match := _KEY.match(line):
            found[match.group(1)] = " ".join(pending) or "(no reason recorded)"
            pending = []
        elif stripped and not stripped.startswith(("}", '"', "'")):
            pending = []
    return found


def main() -> None:
    tasks = {t.task_id: (split, t) for split in ("train", "val", "test") for t in load_split(split)}
    aliases = load_answer_aliases()
    why = reasons()
    lines = [
        "# Dataset corrections: human review sheet",
        "",
        "Generated by `scripts/dataset_review_sheet.py` from",
        "`scripts/apply_dataset_corrections.py`. An automated audit rewrote these",
        f"{len(CORRECTIONS)} tasks because their gold answer was wrong, had gone stale, or",
        "had more than one defensible answer. Nobody has checked them by hand yet.",
        "",
        "For each task: confirm the answer against a reliable source and that the",
        "question now has exactly one correct answer, then tick the box. Note",
        "anything wrong under the task and fix it in `apply_dataset_corrections.py`.",
        "",
        "Test-split tasks matter most: they decide the reported results.",
        "",
    ]
    order = {"test": 0, "val": 1, "train": 2}
    for task_id in sorted(CORRECTIONS, key=lambda t: (order[tasks[t][0]], t)):
        split, task = tasks[task_id]
        accepted = ", ".join(f"`{a}`" for a in aliases.get(task_id, ())) or "none"
        lines += [
            f"## [ ] {task_id} ({split})",
            "",
            f"- **Why changed:** {why.get(task_id, '(no reason recorded)')}",
            f"- **Question:** {task.question}",
        ]
        if task.context:
            lines.append(f"- **Context:** {task.context}")
        lines += [
            f"- **Gold answer:** {task.ground_truth}",
            f"- **Also accepted:** {accepted}",
            "- **Reviewer notes:**",
            "",
        ]
    if WATCHLIST:
        lines += [
            "# Still debatable (not corrected)",
            "",
            "A scan of every gold answer for hedging, very long answers and time-sensitive",
            "wording found these. Decide whether to rewrite or drop them.",
            "",
        ]
    for task_id, note in WATCHLIST.items():
        split, task = tasks[task_id]
        accepted = ", ".join(f"`{a}`" for a in aliases.get(task_id, ())) or "none"
        lines += [
            f"## [ ] {task_id} ({split})",
            "",
            f"- **Concern:** {note}",
            f"- **Question:** {task.question}",
            f"- **Gold answer:** {task.ground_truth}",
            f"- **Also accepted:** {accepted}",
            "- **Reviewer notes:**",
            "",
        ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"[OK] wrote {OUT} ({len(CORRECTIONS)} tasks)")


if __name__ == "__main__":
    main()
