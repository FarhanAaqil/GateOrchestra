"""
scripts/analyze_final_results.py
================================
Turn the final benchmark's checkpoints into the analyses in
evaluation/final_analysis.py, with no further LLM calls.

    python scripts/analyze_final_results.py            # full benchmark
    python scripts/analyze_final_results.py --n 5      # a --n 5 smoke run

Writes reports/final_analysis.json and reports/final_analysis.md. Works on a
partial run too; sections whose data does not exist yet are left out.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from evaluation.final_analysis import analyse  # noqa: E402
from shared.config import (  # noqa: E402
    FINAL_CHECKPOINTS_DIR,
    FINAL_REPORTS_DIR,
    FINAL_RESULTS_DIR,
)
from shared.data_loader import load_split  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CHECKPOINTS = FINAL_CHECKPOINTS_DIR
RESULTS = FINAL_RESULTS_DIR
REPORTS = FINAL_REPORTS_DIR


def _pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}%"


def _pts(x: float | None) -> str:
    return "not detectable" if x is None else f"{x:.1f} pts"


def _ci(rate: dict[str, Any]) -> str:
    low, high = rate["ci95"]
    return f"{_pct(rate['accuracy'])} [{_pct(low, 0)}, {_pct(high, 0)}]"


def render_markdown(a: dict[str, Any]) -> str:
    lines = ["# Final benchmark analysis", ""]
    lines += [
        "Generated by `scripts/analyze_final_results.py` from the benchmark checkpoints;",
        "no extra LLM calls. Calibration (train + validation) data comes from seed "
        f"{a['calibration_seed']}; test data from seeds {', '.join(map(str, a['seeds']))}.",
        "",
    ]
    if p := a.get("premise"):
        lines += [
            "## Is MAS better than CoT-SC? (the premise)",
            "",
            f"{p['n_tasks']} train/validation tasks, {p['n_runs']} graded runs per system.",
            "",
            "| | Accuracy [95% CI] | Avg tokens | Tokens per correct answer |",
            "|:--|:--|--:|--:|",
            f"| CoT-SC | {_ci(p['cot_sc'])} | {p['cot_sc']['avg_tokens']:.0f} "
            f"| {p['tokens_per_correct']['cot_sc']:.0f} |",
            f"| MAS | {_ci(p['mas'])} | {p['mas']['avg_tokens']:.0f} "
            f"| {p['tokens_per_correct']['mas']:.0f} |",
            "",
            f"MAS minus CoT-SC: {p['accuracy_gain_pts']:+.1f} pts; MAS costs "
            f"{p['token_ratio']:.2f}x the tokens. Per task, MAS was more accurate on "
            f"{p['tasks_mas_better']}, less accurate on {p['tasks_cot_better']} and tied on "
            f"{p['tasks_tied']} (sign test p = {p['sign_test_p']:.3f}).",
            "",
        ]
    for key, title in (
        ("oracle_gate_calibration", "train/validation"),
        ("oracle_gate_test", "test, first seed"),
    ):
        if o := a.get(key):
            lines += [
                f"**Oracle gate ({title})** - escalating exactly when MAS is right and CoT-SC "
                f"wrong: accuracy {_ci(o)}, escalation rate {_pct(o['escalate_rate'])}, "
                f"{o['token_savings_vs_mas_pct']:.1f}% fewer tokens than Always-MAS. "
                "No gate can beat this with these two systems.",
                "",
            ]
    if ax := a.get("axis"):
        lines += [
            "## Where MAS helps: Depth x Parallel",
            "",
            "| Cell | Tasks | CoT-SC | MAS | MAS gain |",
            "|:--|--:|--:|--:|--:|",
        ]
        for row in ax["depth_parallel"]:
            lines.append(
                f"| {row['key']} | {row['n_tasks']} | {_pct(row['cot_sc_accuracy'], 0)} "
                f"| {_pct(row['mas_accuracy'], 0)} | {row['mas_gain_pts']:+.0f} pts |"
            )
        lines += ["", "| Source | Tasks | CoT-SC | MAS | MAS gain |", "|:--|--:|--:|--:|--:|"]
        for row in ax["source"]:
            lines.append(
                f"| {row['key']} | {row['n_tasks']} | {_pct(row['cot_sc_accuracy'], 0)} "
                f"| {_pct(row['mas_accuracy'], 0)} | {row['mas_gain_pts']:+.0f} pts |"
            )
        lines.append("")
    if fa := a.get("feature_ablation"):
        lines += [
            "## Gate feature ablation (validation, retrained on real labels)",
            "",
            f"ESCALATE labels: {_pct(fa['escalate_label_share'])} of training tasks.",
            "",
        ]
        if fa.get("rows"):
            lines += [
                "| Classifier | Feature removed | Accuracy | Token savings | Escalation |",
                "|:--|:--|--:|--:|--:|",
            ]
            for r in fa["rows"]:
                lines.append(
                    f"| {r['classifier']} | {r['dropped']} | {_pct(r['accuracy'])} "
                    f"| {r['token_savings_pct']:.1f}% | {_pct(r['escalation_rate'])} |"
                )
        else:
            lines.append(f"Not run: {fa.get('note')}.")
        lines.append("")
    if cands := a.get("calibration_candidates"):
        lines += [
            "## Calibration sweep (validation)",
            "",
            "| Classifier | tau | k | Accuracy | Savings | Escalation |",
            "|:--|--:|--:|--:|--:|--:|",
        ]
        for c in cands:
            lines.append(
                f"| {c['classifier']} | {c['tau_acc']} | {c['k']} | {_pct(c['accuracy'])} "
                f"| {c['token_savings_pct']:.1f}% | {_pct(c['escalation_rate'])} |"
            )
        lines.append("")
    if e := a.get("error_analysis"):
        lines += [
            "## Error analysis (test, all seeds)",
            "",
            "| Method | Failure types |",
            "|:--|:--|",
        ]
        for method, counts in e["failure_types"].items():
            lines.append(
                f"| {method} | " + ", ".join(f"{k}: {v}" for k, v in counts.items()) + " |"
            )
        lines += [
            "",
            "CoT-SC -> MAS on the same task: "
            + ", ".join(f"{k}: {v}" for k, v in e["cot_to_mas"].items()),
            "",
        ]
        if e["examples"]:
            lines += [
                "| Seed | Task | Change | Gold | CoT-SC | MAS (agent) |",
                "|:--|:--|:--|:--|:--|:--|",
            ]
            for x in e["examples"]:
                lines.append(
                    f"| {x['seed']} | {x['task_id']} | {x['change']} | {x['gold']} "
                    f"| {str(x['cot_sc'])[:60]} | {str(x['mas'])[:60]} ({x['mas_strategy']}) |"
                )
            lines.append("")
    if routing := a.get("routing"):
        lines += ["## Learned MAS router", ""]
        for seed, r in routing.items():
            if not r:
                continue
            for phase, arms in r.items():
                text = (
                    ", ".join(
                        f"{arm} {v['n']} runs ({_pct(v['accuracy'], 0)} correct)"
                        for arm, v in arms.items()
                    )
                    or "no MAS runs"
                )
                lines.append(f"- seed {seed}, {phase}: {text}")
        lines.append("")
    if len_ := a.get("lenient"):
        lines += [
            "## Sensitivity: lenient grading",
            "",
            "Strict grading is what the results use. As a check on wordy answers and leaked",
            "action syntax, this also counts an answer as right when the gold answer or an",
            "alias appears as a whole phrase in an answer of at most 25 words with no negation.",
            "",
        ]
        if lp := len_.get("premise"):
            lines += [
                f"Premise, lenient: CoT-SC {_ci(lp['cot_sc'])}, MAS {_ci(lp['mas'])} "
                f"({lp['accuracy_gain_pts']:+.1f} pts; per task MAS better on {lp['tasks_mas_better']}, "
                f"worse on {lp['tasks_cot_better']}, sign test p = {lp['sign_test_p']:.3f}).",
                "",
            ]
        if lt := len_.get("test"):
            lines += ["| Method (test, all seeds) | Strict | Lenient |", "|:--|--:|--:|"]
            for method, v in lt.items():
                lines.append(f"| {method} | {_ci(v['strict'])} | {_ci(v['lenient'])} |")
            lines.append("")
    if b := a.get("budget"):
        lines += [
            "## Budget enforcement",
            "",
            f"{b['over_budget']} of {b['n']} train/validation MAS runs ({b['over_budget_pct']:.1f}%) "
            f"spent more than k x probe tokens, by at most {b['max_overshoot_pct']:.1f}% "
            f"(mean {b['mean_overshoot_pct_when_over']:.1f}% when over). The cap is checked "
            "against a chars/4 estimate of each prompt before the call.",
            "",
        ]
    if pw := a.get("power"):
        lines += [
            "## Statistical power (McNemar vs Always-MAS, alpha 0.05, power 0.8)",
            "",
            "| Method | Observed diff | Discordant | Detectable per seed | Detectable pooled* |",
            "|:--|--:|--:|--:|--:|",
        ]
        for r in pw:
            if r.get("n_pairs_pooled"):
                lines.append(
                    f"| {r['method']} | {r['observed_diff_pts']:+.1f} pts | {_pct(r['discordant_rate'], 0)} "
                    f"| {_pts(r['mde_pts_per_seed'])} | {_pts(r['mde_pts_pooled'])} |"
                )
        lines += [
            "",
            "*Pooling seeds reuses the same test tasks, so the pooled figure is optimistic.",
            "",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--n", type=int, default=None, help="match the benchmark's --n")
    parser.add_argument("--checkpoints", type=Path, default=CHECKPOINTS)
    parser.add_argument("--results", type=Path, default=RESULTS)
    parser.add_argument("--out", type=Path, default=REPORTS)
    args = parser.parse_args()

    tasks = {t.task_id: t for split in ("train", "val", "test") for t in load_split(split)}
    analysis = analyse(args.checkpoints, args.results, tasks, str(args.n or "all"))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "final_analysis.json").write_text(
        json.dumps(analysis, indent=2, default=str), encoding="utf-8"
    )
    (args.out / "final_analysis.md").write_text(render_markdown(analysis), encoding="utf-8")
    print(f"[OK] wrote {args.out / 'final_analysis.md'} and final_analysis.json")


if __name__ == "__main__":
    main()
